  /// Convert a locale code like "en-GB" to "English (UK)".
  /// Falls back to the raw code for unknown languages/regions.
  static String displayName(String localeCode) {
    // Handle formats: "en-GB", "en_GB", "en"
    final parts = localeCode.replaceAll('_', '-').split('-');
    final langCode = parts.first.toLowerCase();
    final langName = _languages[langCode] ?? langCode;

    if (parts.length > 1) {
      final regionCode = parts[1].toUpperCase();
      final regionName = _regions[regionCode] ?? regionCode;
      return '$langName ($regionName)';
    }

    return langName;
  }
