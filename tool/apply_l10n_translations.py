def main() -> None:
    en = json.loads((L10N / "app_en.arb").read_text(encoding="utf-8"))
    en_keys = {k for k in en if not k.startswith("@")}

    for locale, mapping in TRANSLATIONS.items():
        path = L10N / f"app_{locale}.arb"
        data = json.loads(path.read_text(encoding="utf-8"))
        missing_from_map = sorted(set(mapping) - en_keys)
        if missing_from_map:
            raise SystemExit(f"{locale}: unknown keys in map: {missing_from_map}")

        updated = 0
        for key, value in mapping.items():
            if data.get(key) != value:
                data[key] = value
                updated += 1
            meta_key = f"@{key}"
            if meta_key in en and meta_key not in data:
                data[meta_key] = en[meta_key]

        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        still_en = [
            k
            for k, v in mapping.items()
            if data.get(k) == en.get(k) and k not in {"moderatorBadge", "experiencedUserBadge", "hfChatBadge", "hfLmStudioBadge", "hfPasteUrlHint"}
        ]
        print(f"{locale}: wrote {updated} updates; identical-to-en leftovers: {len(still_en)}")
        if still_en:
            print(" ", still_en)


if __name__ == "__main__":
    main()
